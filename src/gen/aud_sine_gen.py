# The PSG's sine table as a ROM. aud_init computes it at runtime with
# libm — lround(-cos(2*pi*i/256) * 32767), phase 0 at the trough — so the
# C header carries the same 256 words, and test_font holds this emission
# entry for entry against the running table.
#
# The RTL takes a quarter of them. A localparam array indexed by a register
# is a mux of constants, and blocks are what this device is short of, so
# the way to make it smaller is to make it shorter. -cos is even
# about the trough and odd about the zero, and lround is odd symmetric, so
# the mirrors are exact and not nearly: entry 128-i is entry i negated and
# entry 256-i is entry i. Sixty-five words from the trough to the peak are
# the whole circle, and aud_psg folds the phase onto them.
#
# Sixteen bits, not eight. At eight the entries quantised to +/-127 and put
# a -49.9 dB floor under every sine the PSG and the bell can make; nothing
# downstream can lift a floor set at the oscillator.

import argparse
import math


def lround(x):
    return math.floor(x + 0.5) if x >= 0 else math.ceil(x - 0.5)


def table():
    return [lround(math.cos(math.pi * 2.0 / 256 * i) * -32767)
            for i in range(256)]


def emit_sv(path):
    t = table()
    with open(path, "w") as f:
        f.write("// Generated by aud_sine_gen.py. Do not edit.\n")
        f.write("package aud_sine_pkg;\n")
        f.write("/* verilator lint_off UNUSEDPARAM */\n")
        q = t[:65]
        f.write(f"localparam logic [15:0] AUD_SINE_Q[{len(q)}] = '{{\n")
        for i in range(0, len(q), 8):
            row = ", ".join(f"16'h{v & 0xFFFF:04X}" for v in q[i:i + 8])
            f.write(f"    {row}{',' if i + 8 < len(q) else ''}\n")
        f.write("};\n")
        f.write("/* verilator lint_on UNUSEDPARAM */\n")
        f.write("endpackage\n")


def emit_h(path):
    t = table()
    with open(path, "w") as f:
        f.write("/* Generated by aud_sine_gen.py. Do not edit. */\n")
        f.write("#include <stdint.h>\n")
        f.write("static const int16_t AUD_SINE_TABLE[256] = {\n")
        for i in range(0, 256, 8):
            row = ", ".join(str(v) for v in t[i:i + 8])
            f.write(f"    {row}{',' if i + 8 < 256 else ''}\n")
        f.write("};\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit-sv")
    ap.add_argument("--emit-h")
    args = ap.parse_args()
    if args.emit_sv:
        emit_sv(args.emit_sv)
    if args.emit_h:
        emit_h(args.emit_h)
