# The numbers a bitstream and a firmware.bin must agree on. Each is
# written here and nowhere else.
#
# REG_VERSION is the register layout and the memory map: everything in
# sw/mmio.h, core/riscv/mem_pkg.sv and sw/link.ld that the bitstream and
# the firmware share. Raise it when a register moves, changes meaning or
# is added and the firmware uses it, or when the map changes. The
# bitstream shows it in a register, and the firmware compares it with
# its own before it uses any other register.
#
# SST_BYTES is the savestate size the bitstream gives the host. The host
# reads that many bytes of the blob window for a save. The firmware's
# savestate must fit in it, which its build checks, and it must fit in
# the window, which stage_map_gate.py checks.

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "core"))
import gen

REG_VERSION = 6
SST_BYTES = 0x60000

NOTE = "Generated by src/host/pocket/gen/version.py -- do not edit.\n"


def emit_h(path):
    with open(path, "w") as f:
        f.write(f"/* {NOTE.strip()} */\n")
        f.write(f"#define POCKET_REG_VERSION {REG_VERSION}\n")
        f.write(f"#define POCKET_SST_BYTES {SST_BYTES:#x}u\n")


def emit_sv(path):
    with open(path, "w") as f:
        f.write(f"// {NOTE}")
        f.write("package pocket_version_pkg;\n")
        f.write(f"localparam logic [31:0] REG_VERSION = 32'd{REG_VERSION};\n")
        f.write(f"localparam logic [31:0] SST_BYTES = 32'h{SST_BYTES:08X};\n")
        f.write("endpackage\n")


if __name__ == "__main__":
    gen.main(c={"pocket_version.h": emit_h},
             sv={"pocket_version_pkg.sv": emit_sv})
