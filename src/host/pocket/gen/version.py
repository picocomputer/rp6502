# The two numbers a bitstream and a firmware.bin must agree on. Each is
# written here and nowhere else. The bitstream shows them in registers
# and the firmware carries them in its image and compares.
#
# SST_VERSION is the savestate blob's format. Raise it when the blob
# changes: its header, what it holds, the order or the size of anything
# in it.
#
# REG_VERSION is the register layout and the memory map: everything in
# sw/mmio.h, core/riscv/mem_pkg.sv and sw/link.ld that the bitstream and
# the firmware share. Raise it when a register moves, changes meaning or
# is added and the firmware uses it, or when the map changes.

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "core"))
import gen

SST_VERSION = 10
REG_VERSION = 1

NOTE = "Generated by src/host/pocket/gen/version.py -- do not edit.\n"


def emit_h(path):
    with open(path, "w") as f:
        f.write(f"/* {NOTE.strip()} */\n")
        f.write(f"#define POCKET_REG_VERSION {REG_VERSION}\n")
        f.write(f"#define POCKET_SST_VERSION {SST_VERSION}\n")


def emit_sv(path):
    with open(path, "w") as f:
        f.write(f"// {NOTE}")
        f.write("package pocket_version_pkg;\n")
        f.write(f"localparam logic [31:0] REG_VERSION = 32'd{REG_VERSION};\n")
        f.write(f"localparam logic [31:0] SST_VERSION = 32'd{SST_VERSION};\n")
        f.write("endpackage\n")


if __name__ == "__main__":
    gen.main(c={"pocket_version.h": emit_h},
             sv={"pocket_version_pkg.sv": emit_sv})
