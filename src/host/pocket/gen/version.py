# The numbers a bitstream and a firmware.bin must agree on. Each is
# written here, except the machine's half of REG_VERSION, which
# src/host/fpga/gen/version.py holds.
#
# REG_VERSION is the register layout and the memory map that the
# bitstream and the firmware share. It is composed: the machine's half,
# MACHINE_VERSION in src/host/fpga/gen/version.py, covers wiring, soc and
# what every FPGA host shares, and HOST_VERSION here covers the Pocket's
# own: pocket_core's host window at 0x80000000, the bridge registers and
# staging layout in sw/bridge.h, and fpga_host.h. Raise HOST_VERSION when
# one of those moves, changes meaning or is added and the firmware uses
# it. The bitstream shows the value in a register, and the firmware
# compares it with its own before it uses any other register.
#
# SST_BYTES is the savestate size the bitstream gives the host. The host
# reads that many bytes of the blob window for a save. The firmware's
# savestate must fit in it, which its build checks, and it must fit in
# the window, which stage_map_gate.py checks.


import build

fpga = build.load_module(build.ROOT / "src/host/fpga/gen/version.py",
                         "fpga_version")

HOST_VERSION = 3
REG_VERSION = fpga.reg_version(fpga.POCKET, HOST_VERSION)
SST_BYTES = 0x60000

NOTE = "Generated by src/host/pocket/gen/version.py -- do not edit.\n"


def emit_h(path):
    with build.open_text(path) as f:
        f.write(f"/* {NOTE.strip()} */\n")
        f.write(f"#define POCKET_REG_VERSION {REG_VERSION:#x}\n")
        f.write(f"#define POCKET_SST_BYTES {SST_BYTES:#x}u\n")


def emit_sv(path):
    with build.open_text(path) as f:
        f.write(f"// {NOTE}")
        # A bench uses what it needs of the package, and core_top, which
        # uses the rest, is never verilated.
        f.write("package pocket_version_pkg;\n")
        f.write("/* verilator lint_off UNUSEDPARAM */\n")
        f.write(f"localparam logic [31:0] REG_VERSION = 32'd{REG_VERSION};\n")
        f.write(f"localparam logic [31:0] SST_BYTES = 32'h{SST_BYTES:08X};\n")
        f.write("/* verilator lint_on UNUSEDPARAM */\n")
        f.write("endpackage\n")


if __name__ == "__main__":
    build.generate(inputs=["src/host/fpga/gen/version.py"],
                   c={"pocket_version.h": emit_h},
                   sv={"pocket_version_pkg.sv": emit_sv})
