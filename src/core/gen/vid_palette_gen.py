# Generates the builtin palette ROMs from src/core/term/color.c: color_2 for
# 1bpp and color_256 for everything else, exactly the tables the mode fills
# fall back to when a config carries no XRAM palette. A C header rides
# along for the parity test, the vid_font_gen pattern.

import argparse
import re
import sys
from pathlib import Path

COLOR_C = Path(__file__).resolve().parents[3] / "src/core/term/color.c"


def rgb8(r, g, b):
    # SCANVIDEO_PIXEL_FROM_RGB8: R at bit 0, alpha bit 5, G bit 6, B bit 11.
    return ((b >> 3) << 11) | ((g >> 3) << 6) | (r >> 3)


ALPHA = 0x0020


def parse_array(text, name, want):
    m = re.search(re.escape(name) + r"\[\d*\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit(f"vid_palette_gen: array {name} not found")
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    vals = []
    for entry in re.finditer(
            r"(SCANVIDEO_ALPHA_MASK\s*\|\s*)?SCANVIDEO_PIXEL_FROM_RGB8\s*\(\s*"
            r"(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)", body):
        v = rgb8(int(entry.group(2)), int(entry.group(3)), int(entry.group(4)))
        if entry.group(1):
            v |= ALPHA
        vals.append(v)
    if len(vals) != want:
        sys.exit(f"vid_palette_gen: {name} has {len(vals)} entries, want {want}")
    return vals


def sv_array(name, data):
    lines = [f"    localparam logic [15:0] {name} [{len(data)}] = '{{"]
    for i in range(0, len(data), 8):
        row = ", ".join(f"16'h{v:04X}" for v in data[i:i + 8])
        sep = "," if i + 8 < len(data) else ""
        lines.append(f"        {row}{sep}")
    lines.append("    };")
    return "\n".join(lines)


def c_array(name, data):
    lines = [f"static const uint16_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 8):
        row = ", ".join(f"0x{v:04X}" for v in data[i:i + 8])
        lines.append(f"    {row},")
    lines.append("};")
    return "\n".join(lines)


HEADER = """\
/*
 * Copyright (c) 2026 Rumbledethumps
 *
 * SPDX-License-Identifier: BSD-3-Clause
 *
 * Generated by vid_palette_gen.py from src/core/term/color.c - do not edit.
 */
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit-sv", metavar="FILE")
    ap.add_argument("--emit-h", metavar="FILE")
    args = ap.parse_args()
    text = COLOR_C.read_text()
    color_2 = parse_array(text, "color_2", 2)
    color_256 = parse_array(text, "const uint16_t color_256", 256)
    if args.emit_sv:
        out = [HEADER, "package vid_palette_pkg;", "",
               "    /* verilator lint_off UNUSEDPARAM */", "",
               sv_array("VID_COLOR_2", color_2), "",
               sv_array("VID_COLOR_256", color_256), "",
               "    /* verilator lint_on UNUSEDPARAM */", "",
               "endpackage", ""]
        Path(args.emit_sv).write_text("\n".join(out))
    if args.emit_h:
        out = [HEADER,
               "#ifndef _VID_PALETTE_TABLES_H_", "#define _VID_PALETTE_TABLES_H_",
               "", "#include <stdint.h>", "",
               c_array("VID_COLOR_2", color_2), "",
               c_array("VID_COLOR_256", color_256), "",
               "#endif /* _VID_PALETTE_TABLES_H_ */", ""]
        Path(args.emit_h).write_text("\n".join(out))


if __name__ == "__main__":
    main()
