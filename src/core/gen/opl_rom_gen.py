# The YM3812's log-sine and exp ROMs for core/aud/opl.c and opl.sv, from
# their formulas in double precision. The exp half is stored as
# (exp | 1024) << 1, the implied one and the doubling the operator applies
# before its shift. No entry lies within 0.0003 of a rounding tie, so the
# rounding is unambiguous.

import argparse
import math

TIE = 1e-4


def rnd(x):
    if abs(x - math.floor(x) - 0.5) < TIE:
        raise SystemExit(f"{x} is too close to a rounding tie")
    return math.floor(x + 0.5)


def tables():
    logsin = [rnd(-math.log2(math.sin((i + 0.5) * math.pi / 512)) * 256)
              for i in range(256)]
    expt = [rnd((2 ** ((255 - i) / 256) - 1) * 1024) for i in range(256)]
    if (logsin[0], logsin[255], expt[0], expt[255]) != (2137, 0, 1018, 0):
        raise SystemExit("the tables do not end where the die's do")
    return logsin + [(e | 1024) << 1 for e in expt]


def emit_h(path, rom):
    with open(path, "w") as f:
        f.write("// Generated by opl_rom_gen.py. Do not edit.\n")
        for i in range(0, len(rom), 16):
            f.write("    " + ", ".join(str(v) for v in rom[i:i + 16]) + ",\n")


def emit_sv(path, rom):
    with open(path, "w") as f:
        f.write("// Generated by opl_rom_gen.py. Do not edit.\n")
        f.write("package opl_rom_pkg;\n")
        f.write("/* verilator lint_off UNUSEDPARAM */\n")
        f.write(f"localparam logic [11:0] OPL_ROM[{len(rom)}] = '{{\n")
        for i in range(0, len(rom), 8):
            row = ", ".join(f"12'd{v}" for v in rom[i:i + 8])
            f.write(f"    {row}{',' if i + 8 < len(rom) else ''}\n")
        f.write("};\n")
        f.write("/* verilator lint_on UNUSEDPARAM */\n")
        f.write("endpackage\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit-h")
    ap.add_argument("--emit-sv")
    a = ap.parse_args()
    if not a.emit_h and not a.emit_sv:
        ap.error("nothing to emit")
    rom = tables()
    if a.emit_h:
        emit_h(a.emit_h, rom)
    if a.emit_sv:
        emit_sv(a.emit_sv, rom)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
