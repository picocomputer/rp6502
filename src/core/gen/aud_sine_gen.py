# The sine table this script emits has to equal the one that sine_init in
# src/core/aud/sine.c computes at run time, and tests/rtl/vga/test_font.cpp
# compares the C header against that table entry for entry.
#
# The entries are sixteen bits because at eight bits they would quantise
# to +/-127, which would put a -49.9 dB floor under every sine the PSG
# and the bell make.

import argparse
import math


def lround(x):
    return math.floor(x + 0.5) if x >= 0 else math.ceil(x - 0.5)


def table():
    return [lround(math.cos(math.pi * 2.0 / 256 * i) * -32767)
            for i in range(256)]


def emit_sv(path):
    t = table()
    with open(path, "w") as f:
        f.write("// Generated by aud_sine_gen.py. Do not edit.\n")
        f.write("package aud_sine_pkg;\n")
        f.write("/* verilator lint_off UNUSEDPARAM */\n")
        f.write(f"localparam logic [15:0] AUD_SINE[{len(t)}] = '{{\n")
        for i in range(0, len(t), 8):
            row = ", ".join(f"16'h{v & 0xFFFF:04X}" for v in t[i:i + 8])
            f.write(f"    {row}{',' if i + 8 < len(t) else ''}\n")
        f.write("};\n")
        f.write("/* verilator lint_on UNUSEDPARAM */\n")
        f.write("endpackage\n")


def emit_h(path):
    t = table()
    with open(path, "w") as f:
        f.write("/* Generated by aud_sine_gen.py. Do not edit. */\n")
        f.write("#include <stdint.h>\n")
        f.write("static const int16_t AUD_SINE_TABLE[256] = {\n")
        for i in range(0, 256, 8):
            row = ", ".join(str(v) for v in t[i:i + 8])
            f.write(f"    {row}{',' if i + 8 < 256 else ''}\n")
        f.write("};\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit-sv")
    ap.add_argument("--emit-h")
    args = ap.parse_args()
    if args.emit_sv:
        emit_sv(args.emit_sv)
    if args.emit_h:
        emit_h(args.emit_h)
