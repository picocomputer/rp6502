# The PSG's sine and pan tables, for psg.c and psg.sv.
#
# The entries are sixteen bits because at eight bits they would quantise
# to +/-127, which would put a -49.9 dB floor under every sine the PSG
# and the bell make.

import argparse
import math


def lround(x):
    return math.floor(x + 0.5) if x >= 0 else math.ceil(x - 0.5)


def table():
    return [lround(math.cos(math.pi * 2.0 / 256 * i) * -32767)
            for i in range(256)]


# The constant-power pan law.
def pan():
    return [lround(1024.0 * math.sqrt(2.0) * math.sin(math.pi / 2 * i / 126))
            for i in range(127)]


def emit_sv(path):
    t = table()
    with open(path, "w") as f:
        f.write("// Generated by aud_sine_gen.py. Do not edit.\n")
        f.write("package aud_sine_pkg;\n")
        f.write("/* verilator lint_off UNUSEDPARAM */\n")
        f.write(f"localparam logic [15:0] AUD_SINE[{len(t)}] = '{{\n")
        for i in range(0, len(t), 8):
            row = ", ".join(f"16'h{v & 0xFFFF:04X}" for v in t[i:i + 8])
            f.write(f"    {row}{',' if i + 8 < len(t) else ''}\n")
        f.write("};\n")
        p = pan()
        f.write(f"localparam logic [10:0] AUD_PAN[{len(p)}] = '{{\n")
        for i in range(0, len(p), 8):
            row = ", ".join(f"11'd{v}" for v in p[i:i + 8])
            f.write(f"    {row}{',' if i + 8 < len(p) else ''}\n")
        f.write("};\n")
        f.write("/* verilator lint_on UNUSEDPARAM */\n")
        f.write("endpackage\n")


def emit_body(path, values):
    with open(path, "w") as f:
        f.write("// Generated by aud_sine_gen.py. Do not edit.\n")
        for i in range(0, len(values), 8):
            f.write("    " + ", ".join(str(v) for v in values[i:i + 8]) + ",\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit-sv")
    ap.add_argument("--emit-h")
    ap.add_argument("--emit-pan-h")
    args = ap.parse_args()
    if args.emit_sv:
        emit_sv(args.emit_sv)
    if args.emit_h:
        emit_body(args.emit_h, table())
    if args.emit_pan_h:
        emit_body(args.emit_pan_h, pan())
