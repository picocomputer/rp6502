# The log-sine table (256x12) and the exp table (256x10) are emitted
# as one 512x12 ROM. The phase generator reads the two at different
# pipeline stages, so one M10K block with two read ports holds both.

import argparse
import math
import re
import sys

ARM = re.compile(r"8'h([0-9a-fA-F]+):\s*out\s*<=\s*(\d+)\s*;")


def lround(x):
    return math.floor(x + 0.5) if x >= 0 else math.ceil(x - 0.5)


def parse_lut(path, width):
    vals = {}
    with open(path) as f:
        for line in f:
            m = ARM.search(line)
            if m:
                vals[int(m.group(1), 16)] = int(m.group(2))
    if sorted(vals) != list(range(256)):
        sys.exit(f"{path}: expected 256 case arms, got {len(vals)}")
    limit = 1 << width
    for k, v in vals.items():
        if v >= limit:
            sys.exit(f"{path}: entry {k} = {v} exceeds {width} bits")
    return [vals[i] for i in range(256)]


def check(name, parsed, formula):
    want = [formula(i) for i in range(256)]
    if parsed != want:
        bad = next(i for i in range(256) if parsed[i] != want[i])
        sys.exit(f"{name}: vendor table diverged from its documented "
                 f"formula at {bad}: {parsed[bad]} vs {want[bad]}")


def log_sine(x):
    return lround(-math.log(math.sin((x + 0.5) * math.pi / 256 / 2))
                  / math.log(2) * 256)


def exp2(x):
    return lround((math.pow(2, x / 256) - 1) * 1024)


def emit_sv(path, table):
    with open(path, "w") as f:
        f.write("// Generated by opl2_lut_gen.py. Do not edit.\n")
        f.write("package opl2_lut_pkg;\n")
        f.write("/* verilator lint_off UNUSEDPARAM */\n")
        f.write("/* log-sine in the low half, exp zero-extended in the"
                " high. */\n")
        f.write("localparam logic [11:0] OPL2_LUT[512] = '{\n")
        for i in range(0, 512, 8):
            row = ", ".join(f"12'h{v:03X}" for v in table[i:i + 8])
            f.write(f"    {row}{',' if i < 504 else ''}\n")
        f.write("};\n")
        f.write("/* verilator lint_on UNUSEDPARAM */\n")
        f.write("endpackage\n")


def emit_h(path, table):
    with open(path, "w") as f:
        f.write("// Generated by opl2_lut_gen.py. Do not edit.\n")
        f.write("#pragma once\n")
        f.write("#include <stdint.h>\n")
        f.write("static const uint16_t OPL2_LUT[512] = {\n")
        for i in range(0, 512, 8):
            row = ", ".join(f"0x{v:03X}" for v in table[i:i + 8])
            f.write(f"    {row},\n")
        f.write("};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--log-sine", required=True)
    ap.add_argument("--exp", required=True)
    ap.add_argument("--emit-sv")
    ap.add_argument("--emit-h")
    args = ap.parse_args()

    ls = parse_lut(args.log_sine, 12)
    ex = parse_lut(args.exp, 10)
    check("log_sine", ls, log_sine)
    check("exp", ex, exp2)
    table = ls + ex

    if args.emit_sv:
        emit_sv(args.emit_sv, table)
    if args.emit_h:
        emit_h(args.emit_h, table)


if __name__ == "__main__":
    main()
