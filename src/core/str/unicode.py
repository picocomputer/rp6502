# The OEM code page tables for core/str/unicode.c, lifted from the vendored
# FatFs ffunicode.c.

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import gen

FFUNICODE = "vendor/fatfs/ffunicode.c"

MAGIC = 0x4F43  # 'O' in the high byte and 'C' in the low byte

# These are all the single-byte code pages in ffunicode.c, in the
# order of its cp_code[] array.
PAGES = [437, 720, 737, 771, 775, 850, 852, 855, 857, 860, 861, 862,
         863, 864, 865, 866, 869]


def parse_words(text):
    return [int(m, 16) for m in re.findall(r"0x([0-9A-Fa-f]{1,4})\b", text)]


def extract_array(src, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*\[\s*\]\s*=\s*\{(.*?)\}\s*;",
                  src, re.S)
    if not m:
        raise SystemExit(f"unicode.py: {name} not found in ffunicode.c")
    return parse_words(m.group(1))


def build():
    src = (gen.ROOT / FFUNICODE).read_text(encoding="utf-8", errors="replace")

    pages = []
    for cp in PAGES:
        t = extract_array(src, f"uc{cp}")
        if len(t) != 128:
            raise SystemExit(f"unicode.py: uc{cp} has {len(t)} entries")
        pages.append(t)

    # The up-case tables end in a zero, which is kept because the loop in
    # ff_wtoupper in core/str/unicode.c stops on it.
    cvt1 = extract_array(src, "cvt1")
    cvt2 = extract_array(src, "cvt2")
    for name, t in (("cvt1", cvt1), ("cvt2", cvt2)):
        if not t or t[-1] != 0:
            raise SystemExit(f"unicode.py: {name} is not zero terminated")

    n = len(PAGES)
    words = [MAGIC, n, len(cvt1), len(cvt2)]
    words += PAGES
    for t in pages:
        words += t
    words += cvt1
    words += cvt2
    return words, n, len(cvt1), len(cvt2)


HEADER = """/* Generated by src/core/str/unicode.py -- do not edit.
 *
 * The OEM code page tables as a flat array of 16-bit words, laid out
 * for a reader that can only fetch one word at a time:
 *
 *   [0] magic, [1] page count, [2] cvt1 words, [3] cvt2 words
 *   [4 ..]            the page numbers, one per page
 *   [4 + n ..]        the pages themselves, 128 words each
 *   then cvt1, then cvt2
 *
 * src/core/str/unicode.c derives every offset from the first four words, so
 * a machine reading this out of a file does not need this header.
 */
"""


def emit_h(path, n, c1, c2, total):
    Path(path).write_text(
        HEADER + f"""
#ifndef _UNICODE_OEM_H_
#define _UNICODE_OEM_H_

#include <stdint.h>

#define UNICODE_OEM_MAGIC 0x{MAGIC:04X}u
#define UNICODE_OEM_PAGES {n}
#define UNICODE_OEM_WORDS {total}
#define UNICODE_OEM_BYTES {total * 2}

#endif /* _UNICODE_OEM_H_ */
""")


def emit_c(path, words):
    # A RIA's binary is copied to RAM at boot, so HOST_IN_FLASH is used
    # to keep these five kilobytes in flash on a RIA.
    out = [HEADER,
           '\n#include "unicode_oem.h"\n#include "core/str/unicode.h"\n'
           '\n#include "machine.h"\n\n',
           'static const HOST_IN_FLASH("unicode_oem") uint16_t'
           " unicode_oem_data[UNICODE_OEM_WORDS] = {\n"]
    for i in range(0, len(words), 12):
        row = ", ".join(f"0x{w:04X}" for w in words[i:i + 12])
        out.append(f"    {row},\n")
    out.append("};\n")
    out.append("""
uint16_t unicode_word(uint32_t index)
{
    return index < UNICODE_OEM_WORDS ? unicode_oem_data[index] : 0;
}
""")
    Path(path).write_text("".join(out))


def emit_bin(path, words):
    b = bytearray()
    for w in words:
        b += bytes((w & 0xFF, w >> 8))
    Path(path).write_bytes(b)


def main():
    words, n, c1, c2 = build()
    gen.main(inputs=[FFUNICODE],
             c={"unicode_oem.h": lambda p: emit_h(p, n, c1, c2, len(words)),
                "unicode_oem.c": lambda p: emit_c(p, words)},
             bin={"unicode_oem.bin": lambda p: emit_bin(p, words)})


if __name__ == "__main__":
    main()
