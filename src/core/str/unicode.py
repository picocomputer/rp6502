# The OEM code page tables for core/str/unicode.c, lifted from the vendored
# FatFs ffunicode.c.

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import gen

FFUNICODE = "vendor/fatfs/ffunicode.c"

# These are all the single-byte code pages in ffunicode.c, in the
# order of its cp_code[] array.
PAGES = [437, 720, 737, 771, 775, 850, 852, 855, 857, 860, 861, 862,
         863, 864, 865, 866, 869]


def parse_words(text):
    return [int(m, 16) for m in re.findall(r"0x([0-9A-Fa-f]{1,4})\b", text)]


def extract_array(src, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*\[\s*\]\s*=\s*\{(.*?)\}\s*;",
                  src, re.S)
    if not m:
        raise SystemExit(f"unicode.py: {name} not found in ffunicode.c")
    return parse_words(m.group(1))


def build():
    src = (gen.ROOT / FFUNICODE).read_text(encoding="utf-8", errors="replace")

    pages = []
    for cp in PAGES:
        t = extract_array(src, f"uc{cp}")
        if len(t) != 128:
            raise SystemExit(f"unicode.py: uc{cp} has {len(t)} entries")
        pages.append(t)

    # The up-case tables end in a zero, which is kept because the loop in
    # ff_wtoupper in core/str/unicode.c stops on it.
    cvt1 = extract_array(src, "cvt1")
    cvt2 = extract_array(src, "cvt2")
    for name, t in (("cvt1", cvt1), ("cvt2", cvt2)):
        if not t or t[-1] != 0:
            raise SystemExit(f"unicode.py: {name} is not zero terminated")

    return pages, cvt1, cvt2


HEADER = """/* Generated by src/core/str/unicode.py -- do not edit.
 *
 * The OEM code page tables of src/core/str/unicode.c: the page numbers,
 * each page's code points for the characters 0x80 to 0xFF, and the two
 * up-case tables, which each end in a zero.
 */
"""


def emit_h(path, pages, cvt1, cvt2):
    Path(path).write_text(
        HEADER + f"""
#ifndef _UNICODE_OEM_H_
#define _UNICODE_OEM_H_

#include <stdint.h>

#define UNICODE_OEM_PAGES {len(pages)}

extern const uint16_t unicode_oem_cp[UNICODE_OEM_PAGES];
extern const uint16_t unicode_oem_page[UNICODE_OEM_PAGES][128];
extern const uint16_t unicode_oem_cvt1[{len(cvt1)}];
extern const uint16_t unicode_oem_cvt2[{len(cvt2)}];

#endif /* _UNICODE_OEM_H_ */
""")


def rows(words, indent):
    return "".join(
        indent + ", ".join(f"0x{w:04X}" for w in words[i:i + 12]) + ",\n"
        for i in range(0, len(words), 12))


def emit_c(path, pages, cvt1, cvt2):
    # On a RIA these five kilobytes stay in flash.
    out = [HEADER,
           '\n#include "unicode_oem.h"\n\n#include "machine.h"\n',
           "\nconst HOST_IN_FLASH uint16_t unicode_oem_cp[] = {\n",
           "    " + ", ".join(str(cp) for cp in PAGES) + ",\n};\n",
           "\nconst HOST_IN_FLASH uint16_t unicode_oem_page[][128] = {\n"]
    for cp, t in zip(PAGES, pages):
        out.append(f"    /* {cp} */\n    {{\n" + rows(t, "        ") + "    },\n")
    out.append("};\n")
    for name, t in (("cvt1", cvt1), ("cvt2", cvt2)):
        out.append(f"\nconst HOST_IN_FLASH uint16_t unicode_oem_{name}[] = {{\n"
                   + rows(t, "    ") + "};\n")
    Path(path).write_text("".join(out))


def main():
    pages, cvt1, cvt2 = build()
    gen.main(inputs=[FFUNICODE],
             c={"unicode_oem.h": lambda p: emit_h(p, pages, cvt1, cvt2),
                "unicode_oem.c": lambda p: emit_c(p, pages, cvt1, cvt2)})


if __name__ == "__main__":
    main()
