# The PCM: device's filter, which only upsamples: from at most 48 kHz to the
# native rate. rsmp's rows suit a ratio near one and leave the band just
# above the input Nyquist frequency half open, so an 8 kHz stream would ring
# with images at 4 to 5 kHz. These rows stop at the input Nyquist frequency
# instead. With BETA's Kaiser window, 48 taps make the transition in about
# 0.19 of it, so FC puts the cutoff that far below.
#
# --report prints the response, as a fraction of the input Nyquist frequency.

import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen
import rsmp

TAPS = 48
FC = 0.90
BETA = 7.2


def check_blend(rs):
    """pcm.c blends adjacent rows in 32 bits: a difference times a 16-bit
    fraction, and half for the rounding."""
    d = max(abs(a - b) for p in range(rsmp.PHASES)
            for a, b in zip(rs[p + 1], rs[p]))
    if d * 0xFFFF + 0x8000 >= 1 << 31:
        raise SystemExit(f"adjacent rows differ by {d}, too much for 32 bits")


def response(rs, x):
    """The gain at x times the input Nyquist frequency of the filter all the
    rows sample, tau input samples from the interpolation point."""
    re = im = 0.0
    for p in range(rsmp.PHASES):
        mu = p / rsmp.PHASES
        for i, c in enumerate(rs[p]):
            tau = (TAPS // 2 - 1) - i + mu
            re += c * math.cos(math.pi * x * tau)
            im += c * math.sin(math.pi * x * tau)
    return math.hypot(re, im) / (rsmp.PHASES << rsmp.Q)


def report(rs):
    db = lambda g: 20 * math.log10(max(g, 1e-12))
    passband = [response(rs, k / 100) for k in range(0, 81, 5)]
    print(f"pcm {rsmp.PHASES} phases x {TAPS} taps, FC {FC}, BETA {BETA}")
    print(f"  0 to 0.80: {db(min(passband)):+.2f} to {db(max(passband)):+.2f} dB")
    for x in (0.85, 0.90, 0.95):
        print(f"  {x:.2f}: {db(response(rs, x)):+.1f} dB")
    stop = max(response(rs, 1.0 + k / 50) for k in range(0, 301))
    print(f"  1.00 to 7.00: {db(stop):+.1f} dB at most")


def emit_h(path, rs):
    with open(path, "w") as f:
        f.write("// Generated by src/core/aud/pcm.py -- do not edit.\n")
        f.write(f"#define PCM_COEF_TAPS {TAPS}\n")
        f.write(f"#define PCM_COEF_PHASES {rsmp.PHASES}\n")
        f.write(f"#define PCM_COEF_Q {rsmp.Q}\n")
        f.write("#ifndef HOST_IN_RAM\n#define HOST_IN_RAM\n#endif\n")
        f.write(f"static const int32_t HOST_IN_RAM pcm_coef[{rsmp.PHASES // 2 + 1}][{TAPS}] = {{\n")
        for row in rs[:rsmp.PHASES // 2 + 1]:
            f.write("    {" + ", ".join(str(c) for c in row) + "},\n")
        f.write("};\n")


def main():
    rs = rsmp.rows(TAPS, FC, BETA)
    rsmp.check(rs)
    rsmp.check_half(rs)
    check_blend(rs)
    a = gen.main(inputs=("src/core/aud/rsmp.py",),
                 c={"pcm_coef.h": lambda p: emit_h(p, rs)},
                 extra=lambda ap: ap.add_argument("--report", action="store_true"))
    if a.report:
        report(rs)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
