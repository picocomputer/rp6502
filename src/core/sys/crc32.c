/* A word's bytes in memory order, the first in the low byte. */
typedef uint32_t crc32_word_t __attribute__((may_alias));

/* MSVC defines neither macro. */
#if defined(__BYTE_ORDER__) && defined(__ORDER_LITTLE_ENDIAN__)
_Static_assert(__BYTE_ORDER__ == __ORDER_LITTLE_ENDIAN__,
               "a word's first byte is its low byte");
#endif

uint32_t host_crc32(uint32_t crc, const void *buf, size_t len)
{
    crc ^= 0xFFFFFFFFu;
    const uint8_t *p = buf;
    for (; len && ((uintptr_t)p & 3u); len--)
        crc = (crc >> 8) ^ crc32_slice[0][(crc ^ *p++) & 0xFFu];
    const uint32_t *t0 = crc32_slice[0], *t1 = crc32_slice[1],
                   *t2 = crc32_slice[2], *t3 = crc32_slice[3];
    if (len >= 4)
    {
        const uint8_t *end = p + (len & ~(size_t)3);
        do
        {
            crc ^= *(const crc32_word_t *)p;
            p += 4;
            crc = t3[crc & 0xFFu] ^ t2[(crc >> 8) & 0xFFu] ^
                  t1[(crc >> 16) & 0xFFu] ^ t0[crc >> 24];
        } while (p != end);
        len &= 3;
    }
    while (len--)
        crc = (crc >> 8) ^ crc32_slice[0][(crc ^ *p++) & 0xFFu];
    return crc ^ 0xFFFFFFFFu;
}
